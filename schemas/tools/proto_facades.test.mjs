import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { create } from "@bufbuild/protobuf";
import { FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";
import { applyFacades, descriptorFiles, facadePlan, forwardExports, generatedExports, modulePath } from "./proto_facades.mjs";

const image = files => descriptorFiles([create(FileDescriptorSetSchema, { file: files })]);
const old = () => image([{ name: "old.proto", package: "example", messageType: [{ name: "Outer",
  nestedType: [{ name: "Inner" }], enumType: [{ name: "State" }] }], service: [{ name: "Api" }] }]);
const next = () => image([{ name: "old.proto", package: "example" }, { name: "new.proto", package: "example",
  messageType: [{ name: "Outer", nestedType: [{ name: "Inner" }], enumType: [{ name: "State" }] }], service: [{ name: "Api" }] }]);
const header = "// @generated by protoc-gen-es v2.12.1 with parameter target=ts\n";
const empty = header + "export const file_old = {};\n";
const generated = header + "export type Outer = {label: string};\nexport const OuterSchema = {};\nexport enum State {}\n";

test("the pre-v1 reference is immutable until an explicit reviewed baseline update", () => {
  const bytes = readFileSync(new URL("../compat/pre-v1.binpb", import.meta.url));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), "5f0b554ad8d1b2ccdf708ff725b8b462d0c19c5ce69d51be73ea8c12bd89be16");
});

test("ownership derives whole-file moves including nested declarations and services", () => {
  assert.deepEqual([...facadePlan(old(), next(), ["old.proto", "new.proto"])], [["old.proto", "new.proto"]]);
  assert.equal(facadePlan(old(), old(), ["old.proto"]).size, 0);
});

test("deletion, partial moves, missing destinations, and duplicate sources fail closed", () => {
  const missing = next(); missing.get("new.proto").service = [];
  assert.throws(() => facadePlan(old(), missing, ["old.proto", "new.proto"]), /removed declaration/);
  const split = next(); split.get("old.proto").service = split.get("new.proto").service; split.get("new.proto").service = [];
  assert.throws(() => facadePlan(old(), split, ["old.proto", "new.proto"]), /split/);
  assert.throws(() => facadePlan(old(), next(), ["old.proto"]), /not generated/);
  assert.throws(() => facadePlan(old(), old(), ["old.proto", "old.proto"]), /duplicate generation/);
});

test("paths and conflicting descriptor copies are rejected", () => {
  for (const path of ["../old.proto", "/old.proto", "a/../old.proto", "a\\old.proto", "x.ts", "a/./b.proto", "a//b.proto"])
    assert.throws(() => modulePath(path));
  const first = create(FileDescriptorSetSchema, { file: [{ name: "x.proto", package: "one" }] });
  assert.equal(descriptorFiles([first, first]).size, 1);
  const second = create(FileDescriptorSetSchema, { file: [{ name: "x.proto", package: "two" }] });
  assert.throws(() => descriptorFiles([first, second]), /conflicting descriptor/);
});

test("facades preserve type/value exports and descriptor identity without any erasure", () => {
  const result = forwardExports(empty, generated, generated, "./new_pb.js", true);
  assert.match(result, /export \{ OuterSchema, State \} from "\.\/new_pb.js"/);
  assert.match(result, /export type \{ Outer \} from "\.\/new_pb.js"/);
  assert.match(result, /export const file_old/);
  assert(!result.includes(" as any"));
  assert.equal(forwardExports(result, generated, generated, "./new_pb.js", true), result);
  const js = forwardExports(empty, generated, generated, "./new_pb.js", false);
  assert(!js.includes("export type"));
});

test("missing/changed exports, retained declarations, and malformed markers fail", () => {
  assert.throws(() => forwardExports(empty, generated, empty, "./new_pb.js", true), /missing or changed/);
  assert.throws(() => forwardExports(generated, generated, generated, "./new_pb.js", true), /shadow/);
  assert.throws(() => forwardExports(empty + "// meridian compatibility exports:start\n", generated, generated, "./new_pb.js", true));
  assert.throws(() => generatedExports(generated.replace("v2.12.1", "v3.0.0")), /generator version/);
});

test("unchanged generation is byte-identical and does not invoke baseline generation", () => {
  const root = mkdtempSync(join(tmpdir(), "meridian-facade-test-"));
  try {
    writeFileSync(join(root, "old_pb.ts"), generated);
    const plan = applyFacades({ baseline: old(), current: old(), sources: ["old.proto"], input: root,
      output: root, mode: "ts", generateBaseline: () => { throw Error("unexpected generation"); } });
    assert.equal(plan.size, 0);
    assert.equal(readFileSync(join(root, "old_pb.ts"), "utf8"), generated);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
