// Compatibility exports come from the frozen descriptors and pinned generator,
// never a hand-maintained list of message or TypeScript names.
import { isMain } from "./cli_entrypoint.mjs";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { fromBinary, toBinary } from "@bufbuild/protobuf";
import { FileDescriptorProtoSchema, FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";

export function modulePath(name) {
  assert(/^[A-Za-z0-9_./-]+\.proto$/.test(name), `invalid proto path: ${name}`);
  assert(!name.startsWith("/") && name.split("/").every(part => part && part !== "." && part !== ".."), `unsafe proto path: ${name}`);
  return name.slice(0, -6) + "_pb";
}

export function descriptorFiles(images) {
  const files = new Map();
  for (const image of images) for (const file of image.file) {
    modulePath(file.name);
    if (files.has(file.name)) assert.deepEqual(toBinary(FileDescriptorProtoSchema, files.get(file.name)),
      toBinary(FileDescriptorProtoSchema, file), `conflicting descriptor: ${file.name}`);
    files.set(file.name, file);
  }
  return files;
}

function ownership(files) {
  const owners = new Map();
  const add = (name, file) => {
    assert(!owners.has(name), `duplicate declaration: ${name}`);
    owners.set(name, file);
  };
  const message = (item, scope, file) => {
    const name = `${scope}.${item.name}`;
    add(name, file);
    for (const nested of item.nestedType) message(nested, name, file);
    for (const enumeration of item.enumType) add(`${name}.${enumeration.name}`, file);
  };
  for (const file of files.values()) {
    for (const item of file.messageType) message(item, file.package, file.name);
    for (const item of [...file.enumType, ...file.service]) add(`${file.package}.${item.name}`, file.name);
  }
  return owners;
}

export function facadePlan(baseline, current, sources) {
  assert.equal(new Set(sources).size, sources.length, "duplicate generation source");
  const selected = new Set(sources);
  for (const name of sources) { modulePath(name); assert(current.has(name), `missing generated descriptor: ${name}`); }
  const before = ownership(baseline), after = ownership(current), plan = new Map();
  for (const file of sources) {
    const destinations = new Set();
    for (const [name, owner] of before) if (owner === file) {
      assert(after.has(name), `removed declaration has no compatible export: ${name}`);
      destinations.add(after.get(name));
    }
    if (!destinations.size || (destinations.size === 1 && destinations.has(file))) continue;
    // This migration co-locates whole compilation units. Partial/split moves
    // require a separately designed symbol mapper, not guessed exports.
    assert.equal(destinations.size, 1, `unsupported split declaration ownership: ${file}`);
    const target = [...destinations][0];
    assert(selected.has(target), `facade destination is not generated: ${target}`);
    assert(!plan.has(target), `chained facade destination: ${target}`);
    plan.set(file, target);
  }
  for (const target of plan.values()) assert(!plan.has(target), `chained facade destination: ${target}`);
  return plan;
}

export function generatedExports(source) {
  assert(source.includes("@generated by protoc-gen-es v2.12.1 "), "unexpected protobuf-es generator version");
  const entries = [...source.matchAll(/^export (?:declare )?(type|const|enum) (\w+)/gm)]
    .map(([, kind, name]) => ({ kind, name })).filter(item => !item.name.startsWith("file_"));
  assert.equal(new Set(entries.map(item => item.name)).size, entries.length, "duplicate generated export");
  return entries;
}

const START = "// meridian compatibility exports:start";
const END = "// meridian compatibility exports:end";
export function forwardExports(source, baselineSource, targetSource, target, declarations) {
  const previous = generatedExports(baselineSource), present = generatedExports(source);
  assert(previous.length, "moved compilation unit has no baseline exports");
  assert.equal(present.length, 0, "a facade must not shadow retained generated declarations");
  const available = new Map(generatedExports(targetSource).map(entry => [entry.name, entry.kind]));
  for (const entry of previous) assert.equal(available.get(entry.name), entry.kind, `missing or changed destination export: ${entry.name}`);
  const values = previous.filter(entry => entry.kind !== "type").map(entry => entry.name);
  const types = declarations ? previous.filter(entry => entry.kind === "type").map(entry => entry.name) : [];
  let clean = source;
  if (source.includes(START) || source.includes(END)) {
    assert.equal(source.split(START).length, 2, "duplicate facade marker");
    assert.equal(source.split(END).length, 2, "invalid facade marker");
    const index = source.indexOf(START);
    assert(source.indexOf(END) > index && !source.slice(source.indexOf(END) + END.length).trim(), "invalid facade suffix");
    clean = source.slice(0, index).replace(/\n+$/, "");
  }
  assert(/^\.\.?\//.test(target) && target.endsWith("_pb.js"), "invalid relative facade target");
  return clean.replace(/\n+$/, "") + `\n\n${START}\n`
    + (values.length ? `export { ${values.join(", ")} } from ${JSON.stringify(target)};\n` : "")
    + (types.length ? `export type { ${types.join(", ")} } from ${JSON.stringify(target)};\n` : "")
    + `${END}\n`;
}

export function applyFacades({ baseline, current, sources, input, output, mode, generateBaseline }) {
  assert(["ts", "js+dts"].includes(mode), "unsupported generation mode");
  const plan = facadePlan(baseline, current, sources);
  const previousRoot = plan.size ? generateBaseline([...plan.keys()], mode) : undefined;
  const extensions = mode === "ts" ? [".ts"] : [".js", ".d.ts"];
  const writes = [];
  for (const name of sources) for (const extension of extensions) {
    const module = modulePath(name), path = join(input, module + extension);
    let source = readFileSync(path, "utf8");
    if (plan.has(name)) {
      const target = modulePath(plan.get(name));
      let specifier = relative(dirname(module), target).replaceAll("\\", "/");
      if (!specifier.startsWith(".")) specifier = "./" + specifier;
      const declarations = extension !== ".js";
      const shapeExtension = extension === ".js" ? ".d.ts" : extension;
      source = forwardExports(source, readFileSync(join(previousRoot, module + shapeExtension), "utf8"),
        readFileSync(join(input, target + shapeExtension), "utf8"), specifier + ".js", declarations);
    }
    writes.push([join(output, module + extension), source]);
  }
  // Validate the entire tree before writes, including missing destination output.
  for (const [path, source] of writes) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, source); }
  return plan;
}

function main(args) {
  const options = { sources: [], images: [] };
  for (let index = 0; index < args.length; index += 2) {
    const key = args[index], value = args[index + 1];
    assert(value, `missing argument: ${key}`);
    if (key === "--source") options.sources.push(value);
    else if (key === "--current-image") options.images.push(value);
    else {
      assert(["--baseline", "--input", "--output", "--mode", "--protoc", "--plugin", "--buf"].includes(key), `unknown argument: ${key}`);
      assert(!options[key.slice(2)], `duplicate argument: ${key}`);
      options[key.slice(2)] = value;
    }
  }
  for (const key of ["baseline", "input", "output", "mode"]) assert(options[key], `missing --${key}`);
  assert(options.images.length && options.sources.length, "descriptor images and generation sources are required");
  const load = path => fromBinary(FileDescriptorSetSchema, readFileSync(path));
  const scratch = mkdtempSync(join(tmpdir(), "meridian-proto-facades-"));
  try {
    const plan = applyFacades({ ...options, baseline: descriptorFiles([load(options.baseline)]),
      current: descriptorFiles(options.images.map(load)), generateBaseline: (sources, mode) => {
        assert(options.plugin && (options.protoc || options.buf), "relocation requires pinned compiler and protobuf-es plugin");
        const command = options.buf ?? options.protoc;
        const args = options.buf ? ["generate", resolve(options.baseline), "--template", JSON.stringify({ version: "v2",
          plugins: [{ local: resolve(options.plugin), out: scratch, opt: [`target=${mode}`, "import_extension=js"] }] }),
          ...sources.flatMap(source => ["--path", source])]
          : [`--descriptor_set_in=${resolve(options.baseline)}`, `--plugin=protoc-gen-es=${resolve(options.plugin)}`,
            `--es_out=${scratch}`, `--es_opt=target=${mode}`, "--es_opt=import_extension=js", ...sources];
        const result = spawnSync(resolve(command), args, { encoding: "utf8" });
        assert.equal(result.status, 0, `baseline generation failed: ${result.error?.message ?? ""}\n${result.stderr}`);
        return scratch;
      } });
    console.log(`Descriptor-derived compatibility facades: ${plan.size}`);
  } finally { rmSync(scratch, { recursive: true, force: true }); }
}
if (isMain(import.meta.url)) main(process.argv.slice(2));
